# Import NumPy for numerical operations and random sensor values.
import numpy as np


# Define readable names for each discrete action.
ACTION_NAMES = [
    "LEFT",
    "FORWARD",
    "RIGHT",
]


# Create a tiny environment to demonstrate an embodied control loop.
class SimpleEnvironment:

    # Initialize the environment.
    def __init__(self, seed=42):
        # Create a reproducible random-number generator.
        self.rng = np.random.default_rng(seed)

        # Start the internal timestep counter at zero.
        self.step_count = 0

        # Generate the first observation.
        self.observation = self._sample_observation()

    # Create one simulated three-sensor observation.
    def _sample_observation(self):
        # Sample three floating-point values between 0 and 1.
        observation = self.rng.random(
            3,
            dtype=np.float32,
        )

        # Return the new sensor observation.
        return observation

    # Return the current observation to the agent.
    def get_observation(self):
        # Return a copy so external code does not modify internal state directly.
        return self.observation.copy()

    # Apply one action and generate the next observation.
    def step(self, action):
        # Increase the timestep counter.
        self.step_count += 1

        # Print the action that the environment receives.
        print(
            "Environment received:",
            ACTION_NAMES[action],
        )

        # Generate the next observation.
        self.observation = self._sample_observation()

        # Return the new observation.
        return self.get_observation()


# Define a simple rule-based policy.
def policy(observation):
    # Select the sensor direction with the largest free distance.
    action = int(
        np.argmax(observation)
    )

    # Return the selected discrete action.
    return action


# Create the environment.
environment = SimpleEnvironment(
    seed=42
)

# Define how many control-loop timesteps will be executed.
NUM_STEPS = 10

# Repeat the observation-action process.
for step in range(NUM_STEPS):
    # Ask the environment for the current observation.
    observation = environment.get_observation()

    # Pass the observation into the policy.
    action = policy(
        observation
    )

    # Print the current loop index.
    print(
        f"\nStep {step}"
    )

    # Print the sensor observation.
    print(
        "Observation:",
        np.round(
            observation,
            3,
        ),
    )

    # Print the action chosen by the policy.
    print(
        "Policy action:",
        ACTION_NAMES[action],
    )

    # Send the action back to the environment.
    next_observation = environment.step(
        action
    )

    # Print the next observation generated by the environment.
    print(
        "Next observation:",
        np.round(
            next_observation,
            3,
        ),
    )

# Print a final completion message.
print(
    "\nObservation-action loop completed."
)
